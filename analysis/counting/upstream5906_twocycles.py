#!/usr/bin/env python3
"""s34: decode the community 7_5906_twoCycles_* files and pin the n=7
2-loop corpus laws. Exit 0 iff every check passes.

RESOLVES the s33 completeness caveat: the twoCycles_* files are
per-string ANNOTATIONS, not extra solutions. Each file's groups are in
perfect 1:1 correspondence with its string file's strings (7/7 files
bijective, 83 groups total): group i = exactly the set of 142 2-loops
its string traverses. The published n=7 5906 corpus therefore IS the 83
strings, and with Kristan's the known corpus is the 84 committed
classes — `m3_check.py -n 7` gates against ALL published data.

Definitions (phase-specific 2-loops; there are n!/(n-1) = 840 at n=7,
they do NOT partition the perms): the 2-loop generated by q visits the
whole 1-cycle of q then jumps weight-2; the jump-composed map
g(q) = q2..q6 q1 q7 yields the loop's 6 generators, so
loop_id(q) = min over the g-orbit. A walk's w2 edge a->b lies on the
loop generated by rot(a). Tuple convention in the files: a tuple t
denotes the loop generated by rot(t) (solved empirically, 142/142 on
the single-string kernel file).

Pinned corpus laws (this script re-verifies them):
  L1 (2-loop count): every known 5906 class — all 84, Kristan's
      included, across ALL SIX L0 allocations — traverses exactly 142
      distinct 2-loops; every known 5907 exactly 143.
  L2 (length identity, corpus-calibrated NOT proven): length =
      n! + (n-1)! + 4 + #2loops = 5764 + L on all 87 walks;
      equivalently waste = (n-1)! - 2 + L. One char = one 2-loop:
      a 5905 in this frame is a 141-2-loop cover.

Usage: python3 upstream5906_twocycles.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, os.pardir, os.pardir))
EXTRA = os.path.join(ROOT, os.pardir, "extraDocs", "known5906_corpus")
N = 7


# s64 P1: g / loop_id / rot are pylib/walkio.py's g / lam / rot.  The local
# g was the n=7 specialization of walkio.g and loop_id was lam's body
# (both take the min of the same 6-element g-orbit at n=7).
import pathlib, sys; sys.path.insert(0, str(next(p for p in pathlib.Path(__file__).resolve().parents if (p / "pylib").is_dir())))  # noqa: E401,E402,E501  <- pylib bootstrap, the ONE sanctioned sys.path line (docs/ARCHITECTURE.md)
from pylib.walkio import g, rot  # noqa: E402,F401
from pylib.walkio import lam as loop_id  # noqa: E402,F401


def parse_groups(path):
    """Mathematica-style nested lists -> list of groups of 7-tuples."""
    groups, depth, cur_group, cur_tuple = [], 0, None, ""
    for ch in open(path).read():
        if ch == "{":
            depth += 1
            if depth == 2:
                cur_group = []
            elif depth == 3:
                cur_tuple = ""
        elif ch == "}":
            if depth == 3:
                cur_group.append(tuple(int(x) for x in cur_tuple.split(",")))
            elif depth == 2:
                groups.append(cur_group)
            depth -= 1
        elif depth == 3:
            cur_tuple += ch
    return groups


# s64 P1: the sixth first_visit_path copy.  pylib's takes n as a parameter
# (the superset signature); this module's callers pass only the string.
from pylib.walkio import first_visit_path as _first_visit_path  # noqa: E402


def first_visit_path(s):
    return _first_visit_path(s, N)


def walk_loops(s):
    path = first_visit_path(s)
    W = set()
    for a, b in zip(path, path[1:]):
        if b[:5] == a[2:]:  # weight-2 edge
            W.add(loop_id(rot(a)))
    return W


def main():
    failures = 0

    # 1) annotation bijection over the community files
    for f in sorted(x for x in os.listdir(EXTRA) if "twoCycles" in x):
        groups = parse_groups(os.path.join(EXTRA, f))
        strings = [
            l.strip()
            for l in open(os.path.join(EXTRA, f.replace("twoCycles_", "")))
            if len(l.strip()) == 5906
        ]
        Ws = [walk_loops(s) for s in strings]
        assigned = set()
        ok = len(groups) == len(strings)
        for grp in groups:
            gl = set(loop_id(rot(t)) for t in grp)
            exact = [
                i for i, W in enumerate(Ws) if len(gl) == 142 and gl == W
            ]
            if len(exact) == 1 and exact[0] not in assigned:
                assigned.add(exact[0])
            else:
                ok = False
        kernel = f.replace("7_5906_twoCycles_nsk", "").replace("_2SYMM_FS.txt", "")
        print(f"{kernel[:28]:30s} {len(groups):3d} groups <-> "
              f"{len(strings):3d} strings: {'BIJECTIVE' if ok else 'MISMATCH'}")
        failures += 0 if ok else 1

    # 2) 2-loop count + length identity over the committed corpus
    for d, want_len, want_loops in (
        (os.path.join(ROOT, "data", "upstream5906"), 5906, 142),
        (os.path.join(ROOT, "data", "upstream5907"), 5907, 143),
    ):
        bad = 0
        files = sorted(x for x in os.listdir(d) if x.endswith(".txt"))
        for x in files:
            s = open(os.path.join(d, x)).read().strip()
            L = len(walk_loops(s))
            if len(s) != want_len or L != want_loops or len(s) != 5764 + L:
                bad += 1
                print(f"  VIOLATION {x}: len={len(s)} loops={L}")
        print(f"{os.path.basename(d)}: {len(files)} walks, "
              f"{'ALL' if not bad else len(files) - bad} at "
              f"{want_loops} loops, length = 5764 + loops "
              f"{'holds' if not bad else 'VIOLATED'}")
        failures += bad

    print("PASS" if not failures else f"FAIL ({failures})")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
