    #[test]
    fn parts_pack_roundtrip() {
        let mut p: PackedParts = 0;
        for (i, &len) in [2u8, 2, 2].iter().enumerate() {
            p = parts_push(p, len);
            assert_eq!(parts_len(p), i + 1);
        }
        assert_eq!(
            (0..3).map(|i| parts_get(p, i)).collect::<Vec<_>>(),
            [2, 2, 2]
        );
    }

    #[test]
    fn profile_prefix_logic() {
        let p = SplitProfile::records_n6();
        // fresh cycle: first part 2, 3, 4 or 6
        assert!(p.part_ok(0, 6, true));
        assert!(p.part_ok(0, 2, false));
        assert!(!p.part_ok(0, 5, false));
        assert!(!p.part_ok(0, 1, false));
        // a completed first part of 2 continues with 4 (complete) or 2 (not)
        let done2 = parts_push(0, 2);
        assert!(p.part_ok(done2, 4, true));
        assert!(p.part_ok(done2, 2, false));
        assert!(!p.part_ok(done2, 2, true));
        assert!(!p.part_ok(done2, 3, false));
        assert_eq!(p.min_more_parts(done2), Some(1));
        assert_eq!(p.min_more_parts(0), Some(1));
        // open-part extension
        assert!(p.open_part_ok(done2, 3)); // can still grow to 4
        assert!(!p.open_part_ok(done2, 5));
    }

    #[test]
    fn small_n_dfs_terminates_and_finds_frontier() {
        // n=4: generous caps, no profile, shallow depth — must terminate
        // without hitting the node cap and produce a nonempty frontier.
        let g = Graph::new(4);
        let dfs = SojournDfs {
            g: &g,
            caps: ClassCaps {
                s: 12,
                d3: 6,
                d4: 0,
                d5: 0,
                ip: 4,
            },
            profile: None,
            depth: 3,
            max_nodes: 5_000_000,
            dedup: DedupMode::Exact,
            exemplars_per_class: 1,
            dump_per_class: 0,
        };
        let st = dfs.run();
        assert!(!st.oversize);
        assert!(st.frontier > 0);
        assert!(st.canonical_classes > 0);
        assert!(st.canonical_classes as u64 <= st.frontier);
        assert!(st.dump.is_empty());
    }

    #[test]
    fn frontier_dump_paths_are_valid_walks() {
        // Dumped seeds must start at rank 0, visit distinct ranks, and
        // rebuild by maximal-overlap concatenation to exactly `len`
        // characters — the contract `beam --seed-file` relies on.
        let g = Graph::new(4);
        let dfs = SojournDfs {
            g: &g,
            caps: ClassCaps {
                s: 12,
                d3: 6,
                d4: 0,
                d5: 0,
                ip: 4,
            },
            profile: None,
            depth: 3,
            max_nodes: 5_000_000,
            dedup: DedupMode::Exact,
            exemplars_per_class: 1,
            dump_per_class: 2,
        };
        let st = dfs.run();
        assert!(!st.dump.is_empty());
        assert!(st.dump.len() as u64 <= 2 * st.canonical_classes as u64);
        let mut per_class: HashMap<u128, u32> = HashMap::new();
        for seed in &st.dump {
            *per_class.entry(seed.class_key).or_insert(0) += 1;
            assert_eq!(seed.path[0], 0);
            let distinct: HashSet<u32> = seed.path.iter().copied().collect();
            assert_eq!(distinct.len(), seed.path.len());
            let mut len = g.n as u32;
            for pair in seed.path.windows(2) {
                let p = &g.perms[pair[0] as usize];
                let q = &g.perms[pair[1] as usize];
                len += (g.n - Graph::overlap(p, q)) as u32;
            }
            assert_eq!(len, seed.len);
        }
        assert!(per_class.values().all(|&c| c <= 2));
    }

