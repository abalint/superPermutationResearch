#!/usr/bin/env python3
"""s35: n-generic 2-loop census — the loop-deficit invariant Λ.

For each corpus walk, count L = distinct 2-loops traversed (a w2 edge
a->b lies on the 2-loop generated by rot(a); loop_id = min over the
jump-composed g-orbit, g(q) = q2..q_{n-1} q1 q_n) and the inter-sojourn
door histogram, then report

    Λ = L + sum_{w>=4} (w-3) * inter[w].

s39: THEOREM (docs/THEORY.md §7) — for every pure complete walk,
length >= n! + (n-1)! + (n-3) + Λ, and equality = the "tight loop
cover" class. This script verifies the corpus sits at EQUALITY:
every known record-length walk at a given n has the SAME Λ, and
    length = n! + (n-1)! + (n-3) + Λ
  - n=6: Λ = 29 on ALL 22,062 classes (L=29 for the pure-w3
    allocations, 28 for the 397 single-w4 classes, 27 for the 18
    double-w4 classes — heavy doors substitute for 2-loops at exactly
    (w-3) loops per door, zero exceptions).
  - n=7: Λ = L = 142 on all 84 known 5906s (pure-w3 corpus);
    143 on the 5907s; Egan's 5908 sits at 144.
So one character = one Λ-unit on the record shell: an 871 is a Λ=28
object, a 5905 is a Λ=141 object. Any improving edit must reduce Λ —
remove a 2-loop or upgrade door weight — not merely repartition.

Usage: python3 loop_census.py -n 6 data/upstream872
       python3 loop_census.py -n 7 data/upstream5906 data/upstream5907
Exit 0 iff every walk of length n!+(n-1)!+(n-3)+K has Λ = K for the
modal K (i.e. the invariant holds; longer walks report their own Λ).
"""
import os
import sys
from collections import Counter
from math import factorial


def main():
    args = sys.argv[1:]
    if len(args) < 3 or args[0] != "-n":
        print(__doc__, file=sys.stderr)
        return 1
    n = int(args[1])
    dirs = args[2:]

    want = set(range(1, n + 1))

    def first_visit_path(s):
        seen, path = set(), []
        vals = [int(c) for c in s]
        for i in range(len(vals) - n + 1):
            win = tuple(vals[i : i + n])
            if set(win) == want and win not in seen:
                seen.add(win)
                path.append(win)
        return path

    def g(p):
        return p[1 : n - 1] + (p[0], p[n - 1])

    def loop_id(p):
        orb = [p]
        for _ in range(n - 2):
            orb.append(g(orb[-1]))
        return min(orb)

    def rot_cycle(p):
        return min(p[i:] + p[:i] for i in range(n))

    hist = Counter()
    for d in dirs:
        for f in sorted(os.listdir(d)):
            if not f.endswith(".txt"):
                continue
            s = open(os.path.join(d, f)).read().strip()
            path = first_visit_path(s)
            loops = set()
            inter = Counter()
            for a, b in zip(path, path[1:]):
                if b[: n - 2] == a[2:]:
                    loops.add(loop_id(a[1:] + (a[0],)))
                if rot_cycle(a) != rot_cycle(b):
                    w = n - max(
                        (k for k in range(n - 1, 0, -1) if a[n - k :] == b[:k]),
                        default=0,
                    )
                    if w >= 3:
                        inter[w] += 1
            lam = len(loops) + sum((w - 3) * c for w, c in inter.items() if w >= 4)
            hist[(len(s), len(loops), tuple(sorted(inter.items())), lam)] += 1

    base = factorial(n) + factorial(n - 1) + (n - 3)
    print(f"(length, L, doors, Λ) histogram; base n!+(n-1)!+(n-3) = {base}")
    violations = 0
    lam_by_len = {}
    for (length, L, doors, lam), c in sorted(hist.items(), key=lambda kv: -kv[1]):
        print(f"len={length} L={L} doors={dict(doors)} Λ={lam}: {c}")
        lam_by_len.setdefault(length, set()).add(lam)
    for length, lams in sorted(lam_by_len.items()):
        ok = lams == {length - base}
        if not ok:
            violations += 1
        print(
            f"length {length}: Λ ∈ {sorted(lams)} "
            f"(identity predicts {length - base}) — "
            f"{'HOLDS' if ok else 'VIOLATED'}"
        )
    return 1 if violations else 0


if __name__ == "__main__":
    sys.exit(main())
