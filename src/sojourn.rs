//! Sojourn-level canonical opening DFS — Track B's L2 layer
//! (`docs/TRACKB-DESIGN.md` §2 L2, §4 step 2).
//!
//! A walk is segmented into *sojourns* (maximal same-rotation-cycle
//! runs). The DFS explores every canonical-reading walk prefix of a
//! given sojourn depth that stays inside an L0 allocation class
//! (`(S, d3, d4, d5, d6, ip)` caps, T0's general waste identity) and,
//! optionally, an L1 split-profile class (allowed per-cycle part
//! compositions, e.g. the records' `6 | 2,4 | 3,3 | 4,2 | 2,2,2`).
//!
//! Moves follow the canonical first-visit grammar established by T0:
//!
//! * **ride** — the weight-1 rotation, if unvisited (never ends a
//!   sojourn);
//! * **skip** — intra-orbit rotate-by-k (k = 2..5, priced k−1 into
//!   `ip`), legal iff the k−1 passed members are all already visited
//!   (T0 canonical-reading lemma) and the landing member is unvisited;
//! * **exit door** — `w2x` (the unique cross-cycle weight-2 edge; no
//!   interior permutation window, always composable) or a cross-cycle
//!   weight-3/4/5 door, priced into `d3/d4/d5`; the emergent-edge
//!   filter (JOURNAL 2026-07-29, atlas T1) skips any door with an
//!   *unvisited* interior permutation window — the same string is
//!   generated by the decomposed line, so pruning is lossless.
//!   Weight-6 doors do not exist in the stored graph (the weight-n
//!   fallback never fires inside a budgeted opening), so `d6 = 0`
//!   classes are exact here.
//!
//! Dedup is exact on `(cur, visited, ledger, per-cycle parts, current
//! part length)` via a 128-bit Zobrist-style hash (deterministic
//! mixing; the collision probability at 10^7 states is ~10^-25 — fine
//! for a feasibility gate, noted with M2 results). The L2 canonical key
//! (relabeling-invariant: per-cycle visit-pattern necklace multiset +
//! ledger + current-cycle pattern) groups frontier states into opening
//! classes — the future bandit arms.

use std::collections::{HashMap, HashSet};

