/// L0 allocation-class caps for the DFS (a prefix must stay completable
/// within them).
#[derive(Clone, Copy, Debug)]
pub struct ClassCaps {
    /// Total sojourn count of the class (S).
    pub s: u16,
    /// Weight-3 door count.
    pub d3: u16,
    /// Weight-4 door count.
    pub d4: u16,
    /// Weight-5 door count.
    pub d5: u16,
    /// Priced intra-skip waste (i2 + 2·i3 + 3·i4 + 4·i5).
    pub ip: u16,
}

impl ClassCaps {
    /// Exact waste of a completed walk with this allocation (d6 = 0).
    pub fn waste(&self) -> u32 {
        (self.s as u32 - 1)
            + self.d3 as u32
            + 2 * self.d4 as u32
            + 3 * self.d5 as u32
            + self.ip as u32
    }
}

/// Completed part lengths of one cycle, packed 3 bits per part
/// (lengths 1..=6, up to 6 parts → 18 bits).
pub type PackedParts = u32;

fn parts_push(p: PackedParts, len: u8) -> PackedParts {
    let k = parts_len(p);
    p | (len as u32) << (3 * k)
}

fn parts_len(p: PackedParts) -> usize {
    let mut k = 0;
    while (p >> (3 * k)) & 0b111 != 0 {
        k += 1;
    }
    k
}

fn parts_get(p: PackedParts, i: usize) -> u8 {
    ((p >> (3 * i)) & 0b111) as u8
}

/// Split-profile constraint: the set of allowed per-cycle part
/// compositions (each a sequence of part lengths summing to n).
#[derive(Clone, Debug)]
pub struct SplitProfile {
    /// Allowed complete compositions, e.g. [[6],[2,4],[3,3],[4,2],[2,2,2]].
    pub allowed: Vec<Vec<u8>>,
}

/// Locate a repo-relative data file without depending on the current
/// working directory.
///
/// Tries `rel` as given first — that is exactly the `--profile-file`
/// convention (a plain cwd-relative path) — then walks up from the
/// running executable, so `target/release/superperm` finds the repo's
/// committed data no matter where it is invoked from. Returns `None`
/// when nothing matches; every caller must have a compiled-in fallback,
/// because no subcommand may acquire a new file-IO failure mode.
fn find_repo_file(rel: &str) -> Option<std::path::PathBuf> {
    let direct = std::path::Path::new(rel);
    if direct.is_file() {
        return Some(direct.to_path_buf());
    }
    let exe = std::env::current_exe().ok()?;
    let mut dir = exe.parent();
    while let Some(d) = dir {
        let cand = d.join(rel);
        if cand.is_file() {
            return Some(cand);
        }
        dir = d.parent();
    }
    None
}

impl SplitProfile {
    /// The committed census file that DEFINES the records allocation's
    /// split profile — the single authority for `--records-profile`
    /// (`docs/CONTRACTS.md` §2, the split-profile contract).
    pub const RECORDS_N6_PROFILE: &'static str = "analysis/trackb/profiles/a145_3_0_0_0.txt";

    /// Records' L1 class at n=6 (ITEM5 §1 table) — the **compiled-in
    /// fallback** for [`Self::records_n6_loaded`], kept so that
    /// `--records-profile` can never fail at file IO (its behaviour
    /// guarantee since s22; see `docs/CONTRACTS.md` §2).
    ///
    /// This constant used to be the *only* definition, forked from the
    /// census data it duplicates. The test
    /// `records_n6_constant_equals_committed_profile_file` now pins it
    /// equal to [`Self::RECORDS_N6_PROFILE`] as a SET of compositions;
    /// the listing order differs and cannot matter, because every
    /// consumer (`part_ok`, `min_more_parts`, `open_part_ok`) quantifies
    /// over `allowed` with `any`/`min`.
    pub fn records_n6() -> Self {
        SplitProfile {
            allowed: vec![vec![6], vec![2, 4], vec![3, 3], vec![4, 2], vec![2, 2, 2]],
        }
    }

    /// What `--records-profile` resolves to: the committed profile file
    /// if it can be found and parsed, else [`Self::records_n6`].
    ///
    /// The fallback is deliberate, not defensive sloppiness: before s64
    /// P6 this flag read a compiled-in table and therefore *never*
    /// touched the filesystem, so a strict load would hand every
    /// out-of-repo invocation a brand-new way to fail. The `#[test]`
    /// keeps the two definitions from drifting, which is the whole point
    /// of the de-fork.
    pub fn records_n6_loaded() -> Self {
        find_repo_file(Self::RECORDS_N6_PROFILE)
            .and_then(|p| Self::from_file(&p, 6).ok())
            .unwrap_or_else(Self::records_n6)
    }

    /// Load an allowed-composition set from a profile file: one
    /// composition per line, part lengths space-separated (e.g. "2 4"),
    /// `#` comments and blank lines skipped. This is the per-allocation
    /// grammar input generated by the s27 corpus census
    /// (`analysis/counting/upstream872_structure.py --profiles-dir`);
    /// the census showed the hard-coded records profile is one of 8
    /// allocation-specific composition sets, so profiles are data now.
    pub fn from_file(path: &std::path::Path, n: u8) -> Result<Self, String> {
        let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
        let mut allowed = Vec::new();
        for (ln, line) in text.lines().enumerate() {
            let line = line.split('#').next().unwrap_or("").trim();
            if line.is_empty() {
                continue;
            }
            let comp: Vec<u8> = line
                .split_whitespace()
                .map(|t| t.parse::<u8>().map_err(|e| format!("line {}: {e}", ln + 1)))
                .collect::<Result<_, _>>()?;
            if comp.iter().any(|&p| p == 0 || p > n)
                || comp.iter().map(|&p| p as u32).sum::<u32>() != n as u32
            {
                return Err(format!(
                    "line {}: composition {comp:?} must have parts in 1..={n} summing to {n}",
                    ln + 1
                ));
            }
            if !allowed.contains(&comp) {
                allowed.push(comp);
            }
        }
        if allowed.is_empty() {
            return Err(format!("{}: no compositions", path.display()));
        }
        Ok(SplitProfile { allowed })
    }

    fn matches_prefix(comp: &[u8], done: PackedParts) -> bool {
        let k = parts_len(done);
        comp.len() >= k && (0..k).all(|i| comp[i] == parts_get(done, i))
    }

    /// May a cycle whose completed parts are `done` accept a further
    /// part of length `next` — and if that completes the cycle, is the
    /// full composition allowed?
    fn part_ok(&self, done: PackedParts, next: u8, completes: bool) -> bool {
        let k = parts_len(done);
        self.allowed.iter().any(|comp| {
            comp.len() > k
                && Self::matches_prefix(comp, done)
                && comp[k] == next
                && (!completes || comp.len() == k + 1)
        })
    }

    /// Minimum number of additional parts needed to complete a cycle
    /// with `done` parts already placed (`None` if impossible).
    fn min_more_parts(&self, done: PackedParts) -> Option<u16> {
        let k = parts_len(done);
        self.allowed
            .iter()
            .filter(|comp| Self::matches_prefix(comp, done))
            .map(|comp| (comp.len() - k) as u16)
            .min()
    }

    /// May the current open part (length `cur`, not yet closed) still
    /// extend into some allowed composition?
    fn open_part_ok(&self, done: PackedParts, cur: u8) -> bool {
        let k = parts_len(done);
        self.allowed
            .iter()
            .any(|comp| comp.len() > k && Self::matches_prefix(comp, done) && comp[k] >= cur)
    }
}

/// DFS configuration.
pub struct SojournDfs<'g> {
    pub g: &'g Graph,
    pub caps: ClassCaps,
    pub profile: Option<SplitProfile>,
    /// Restrict weight-3/4/5 doors to untouched cycles (see
    /// [`Grammar::fresh_doors`]; corpus-calibrated, off by default).
    pub fresh_doors: bool,
    /// Stop expanding once this many sojourns are *complete* (doors
    /// taken); the resulting states form the opening frontier.
    pub depth: u16,
    /// Hard node budget; the search reports honestly when it is hit
    /// (`open-oversize` per TRACKB-DESIGN §4.2 — no silent truncation).
    pub max_nodes: u64,
    /// Dedup tier (see [`DedupMode`]).
    pub dedup: DedupMode,
    /// [`DedupMode::Abstraction`] only: expand up to this many exact
    /// exemplars per canonical class (1 = classic exemplar expansion;
    /// higher values trade nodes for class coverage — s22 measured the
    /// coverage curve against exact ground truth).
    pub exemplars_per_class: u32,
    /// Emit up to this many frontier exemplars per canonical class into
    /// [`DfsStats::dump`], each carrying its full first-visit rank path
    /// (T3 seeds for `beam --seed-file`). 0 = off (states then carry no
    /// path and clone as cheaply as before).
    pub dump_per_class: u32,
}

/// How DFS states are deduplicated.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DedupMode {
    /// Exact on `(cur, visited, ledger, parts, cur_part)`. Sound; no
    /// symmetry reduction.
    Exact,
    /// Quotient by symbol relabeling — the L2 design's "deduped up to
    /// symbol relabeling". Sound for exhaustion up to symmetry: a
    /// relabeling is a graph automorphism commuting with cycles, `w2x`,
    /// door weights, interior windows, and the split profile, so
    /// relabeling-related states have isomorphic futures. The canonical
    /// form is O(1) to pick: exactly one relabeling maps `cur` to the
    /// identity permutation (τ = cur⁻¹), so the key is the τ-image of
    /// the state.
    Orbit,
    /// One exemplar per L2 canonical key (necklace-multiset
    /// abstraction). Coarsest; organizes the opening book / bandit arms
    /// but is NOT exhaustion-sound — same-key states need not be
    /// relabelings of each other, and at depth 4 this tier already
    /// reaches only ~half the true classes (measured s22).
    Abstraction,
}

/// Search state (cloned per child; opening depth keeps this cheap).
/// Shared between the exhaustive DFS and the NRPA rollouts
/// (`crate::nrpa`), which read the counters as move features.
///
/// The visit bookkeeping (visited set, per-cycle unvisited counts,
/// current permutation, emitted length, `k`/`r`/`intact`) is the shared
/// [`CycleState`] (s64 P3) — `cyc.intact` is what this searcher used to
/// call `untouched`. Only the sojourn ledger below is local.
#[derive(Clone)]
pub(crate) struct State {
    /// The shared per-cycle visit bookkeeping.
    pub(crate) cyc: CycleState,
    /// Sojourns started so far (= doors taken + 1).
    pub(crate) s: u16,
    pub(crate) d3: u16,
    pub(crate) d4: u16,
    pub(crate) d5: u16,
    pub(crate) ip: u16,
    /// Completed part lengths per cycle (current open part excluded).
    pub(crate) parts: Vec<PackedParts>,
    /// Members covered by the current (open) sojourn.
    pub(crate) cur_part: u8,
    /// First-visit rank path (starts with rank 0); tracked only when
    /// frontier dumping is on, `None` otherwise.
    pub(crate) path: Option<Vec<u32>>,
}

/// One legal move out of a sojourn state.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct SojournMove {
    /// Rank of the permutation the move lands on.
    pub(crate) target: u32,
    pub(crate) kind: MoveKind,
}

/// Move species of the canonical first-visit grammar.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum MoveKind {
    /// Weight-1 rotation within the current cycle.
    Ride,
    /// Intra-orbit rotate-by-k (k−1 priced into `ip`).
    Skip(u16),
    /// Cross-cycle exit door of this weight (2 = `w2x`).
    Door(u8),
}

/// The sojourn move grammar of one L0/L1 class: caps + optional split
/// profile + the emergent-edge interior tables. The single source of
/// truth for legal moves, used by both the exhaustive DFS
/// ([`SojournDfs`]) and the NRPA rollouts (`crate::nrpa`) — one
/// generator, no grammar divergence.
pub struct Grammar<'g> {
    pub g: &'g Graph,
    pub caps: ClassCaps,
    pub profile: Option<SplitProfile>,
    /// Corpus-calibrated door cap (s27 door-pricing census): allow
    /// weight-3/4/5 doors only into untouched cycles. All 66,999 heavy
    /// doors across the 22,062 community classes open a fresh cycle —
    /// re-entries into split cycles always use `w2x` — so this prune
    /// keeps every known 872 in-grammar. Like the split profile it is
    /// an empirical regularity of the corpus, not a theorem: off by
    /// default; exhaustion claims made with it on must say so.
    pub fresh_doors: bool,
    interiors: Vec<Vec<Vec<u32>>>,
}

impl<'g> Grammar<'g> {
    pub fn new(g: &'g Graph, caps: ClassCaps, profile: Option<SplitProfile>) -> Self {
        Grammar {
            g,
            caps,
            profile,
            fresh_doors: false,
            interiors: build_interiors(g),
        }
    }

    /// Root state at the identity permutation.
    pub(crate) fn root(&self, track_path: bool) -> State {
        let g = self.g;
        State {
            cyc: CycleState::root(g, None),
            s: 1,
            d3: 0,
            d4: 0,
            d5: 0,
            ip: 0,
            parts: vec![0; g.cycle_count],
            cur_part: 1,
            path: track_path.then(|| vec![0]),
        }
    }

    /// Replay a first-visit rank path (identity root excluded) through
    /// the grammar, returning how many moves are legal in sequence.
    /// `seq.len()` means the walk lives entirely inside this
    /// caps+profile grammar — the s25 record-replay check, now a public
    /// instrument (the `grammar-check` subcommand) so per-allocation
    /// grammars can be validated against corpus specimens.
    pub fn replay(&self, seq: &[u32]) -> usize {
        let mut st = self.root(false);
        for (done, &target) in seq.iter().enumerate() {
            let kids = self.children(&st);
            match kids.into_iter().find(|(mv, _)| mv.target == target) {
                Some((_, next)) => st = next,
                None => return done,
            }
        }
        seq.len()
    }

    /// All feasible children of `st`, in the DFS push order (ride,
    /// skips by ascending k, `w2x`, stored doors in `g.succs` order).
    /// Empty when the walk is complete or dead-ended.
    pub(crate) fn children(&self, st: &State) -> Vec<(SojournMove, State)> {
        let g = self.g;
        let n = g.n;
        let mut kids = Vec::new();
        // `r == 0` iff every permutation is visited (the shared state's
        // `r` is the maintained complement of the visited popcount).
        if st.cyc.r == 0 {
            return kids;
        }
        let cid = g.cycle_id[st.cyc.cur as usize] as usize;

        // ride
        let r1 = g.succ1(st.cyc.cur);
        if !st.cyc.visited.get(r1 as usize) {
            let mut c = st.clone();
            c.advance_within(g, r1, 1);
            if self.feasible(&c) {
                kids.push((
                    SojournMove {
                        target: r1,
                        kind: MoveKind::Ride,
                    },
                    c,
                ));
            }
        }

        // skips (rotate-by-k): passed members must be visited, landing
        // unvisited; priced k-1 into ip
        if st.ip < self.caps.ip {
            let mut passed = st.cyc.cur;
            for k in 2..n as u16 {
                passed = g.succ1(passed); // member at rotation k-1
                if !st.cyc.visited.get(passed as usize) {
                    break; // T0 lemma: cannot pass an unvisited member
                }
                if st.ip + (k - 1) > self.caps.ip {
                    break;
                }
                let target = g.succ1(passed);
                if st.cyc.visited.get(target as usize) {
                    continue;
                }
                let mut c = st.clone();
                c.ip += k - 1;
                c.advance_within(g, target, k as u32);
                if self.feasible(&c) {
                    kids.push((
                        SojournMove {
                            target,
                            kind: MoveKind::Skip(k),
                        },
                        c,
                    ));
                }
            }
        }

        // exit doors: w2x, then stored w3..w5 cross-cycle doors
        let w2t = g.w2x[st.cyc.cur as usize];
        if !st.cyc.visited.get(w2t as usize) {
            if let Some(c) = self.door_child(st, w2t, 2, cid) {
                kids.push((
                    SojournMove {
                        target: w2t,
                        kind: MoveKind::Door(2),
                    },
                    c,
                ));
            }
        }
        for (si, &(q, w)) in g.succs[st.cyc.cur as usize].iter().enumerate() {
            if w < 3 {
                continue;
            }
            let over = match w {
                3 => st.d3 >= self.caps.d3,
                4 => st.d4 >= self.caps.d4,
                _ => st.d5 >= self.caps.d5,
            };
            if over || g.cycle_id[q as usize] as usize == cid || st.cyc.visited.get(q as usize) {
                continue;
            }
            // fresh-doors cap: heavy doors only open untouched cycles
            if self.fresh_doors
                && (st.cyc.cycle_rem[g.cycle_id[q as usize] as usize] as usize) != g.n
            {
                continue;
            }
            // emergent-edge filter: an unvisited interior perm means the
            // decomposed line builds the same string — skip the composed edge
            if self.interiors[st.cyc.cur as usize][si]
                .iter()
                .any(|&ir| !st.cyc.visited.get(ir as usize))
            {
                continue;
            }
            if let Some(c) = self.door_child(st, q, w, cid) {
                kids.push((
                    SojournMove {
                        target: q,
                        kind: MoveKind::Door(w),
                    },
                    c,
                ));
            }
        }
        kids
    }

    fn door_child(&self, st: &State, target: u32, w: u8, exit_cid: usize) -> Option<State> {
        let g = self.g;
        // the exit closes the current part on the exited cycle
        let completes = st.cyc.cycle_rem[exit_cid] == 0;
        if let Some(p) = &self.profile {
            if !p.part_ok(st.parts[exit_cid], st.cur_part, completes) {
                return None;
            }
        }
        let mut c = st.clone();
        c.parts[exit_cid] = parts_push(c.parts[exit_cid], st.cur_part);
        c.s += 1;
        match w {
            2 => {}
            3 => c.d3 += 1,
            4 => c.d4 += 1,
            _ => c.d5 += 1,
        }
        c.cyc.visit(g, target, w as u32, None);
        c.cur_part = 1;
        if let Some(p) = c.path.as_mut() {
            p.push(target);
        }
        self.feasible(&c).then_some(c)
    }

    /// Completability of the class caps from this prefix.
    fn feasible(&self, st: &State) -> bool {
        if st.s > self.caps.s
            || st.d3 > self.caps.d3
            || st.d4 > self.caps.d4
            || st.d5 > self.caps.d5
            || st.ip > self.caps.ip
        {
            return false;
        }
        let g = self.g;
        let cid = g.cycle_id[st.cyc.cur as usize] as usize;
        // every untouched cycle and every partial non-active cycle owes
        // >= 1 more sojourn (sharper with a split profile)
        let mut owed = st.cyc.intact as u64;
        if let Some(p) = &self.profile {
            for c in 0..g.cycle_count {
                if st.cyc.cycle_rem[c] == 0 || st.cyc.cycle_rem[c] as usize == g.n || c == cid {
                    continue;
                }
                match p.min_more_parts(st.parts[c]) {
                    Some(m) => owed += m as u64,
                    None => return false,
                }
            }
            if !p.open_part_ok(st.parts[cid], st.cur_part) {
                return false;
            }
        } else {
            for c in 0..g.cycle_count {
                if st.cyc.cycle_rem[c] != 0 && (st.cyc.cycle_rem[c] as usize) < g.n && c != cid {
                    owed += 1;
                }
            }
        }
        st.s as u64 + owed <= self.caps.s as u64
    }
}

/// Aggregate results.
pub struct DfsStats {
    /// States expanded (post-dedup).
    pub nodes: u64,
    /// Frontier states at the sojourn depth.
    pub frontier: u64,
    /// Distinct L2 canonical classes on the frontier.
    pub canonical_classes: usize,
    /// True if `max_nodes` was hit (all counts are then lower bounds).
    pub oversize: bool,
    /// States with no legal move before reaching the depth.
    pub dead_ends: u64,
    /// Walks completed inside the horizon (all perms visited).
    pub completed: u64,
    /// Frontier exemplars (≤ `dump_per_class` per canonical class),
    /// empty unless dumping is on.
    pub dump: Vec<FrontierSeed>,
}

/// One dumped frontier exemplar — a beam seed (T3).
pub struct FrontierSeed {
    /// L2 canonical key of its opening class.
    pub class_key: u128,
    /// Characters emitted so far.
    pub len: u32,
    /// Ledger at the frontier: sojourns started, door counts, priced
    /// intra-skip waste.
    pub s: u16,
    /// Weight-3 doors taken.
    pub d3: u16,
    /// Weight-4 doors taken.
    pub d4: u16,
    /// Weight-5 doors taken.
    pub d5: u16,
    /// Priced intra-skip waste.
    pub ip: u16,
    /// First-visit rank path from the identity (starts with rank 0).
    pub path: Vec<u32>,
}

/// Precomputed relabeling machinery for [`DedupMode::Orbit`].
struct OrbitTables {
    /// `apply[t][r]` = rank of the word obtained by relabeling
    /// `perms[r]`'s symbols through the map `s -> perms[t][s-1]`.
    apply: Vec<Vec<u32>>,
    /// Rank of the inverse permutation of `perms[r]` — the unique
    /// relabeling mapping `perms[r]` to the identity.
    inv_rank: Vec<u32>,
    /// `cycle_map[t][c]` = image cycle of cycle `c` under relabeling `t`.
    cycle_map: Vec<Vec<u32>>,
}

impl OrbitTables {
    fn new(g: &Graph, reps: &[u32]) -> Self {
        let n = g.n;
        let apply: Vec<Vec<u32>> = (0..g.nfact)
            .map(|t| {
                let tau = &g.perms[t];
                (0..g.nfact)
                    .map(|r| {
                        let w: Vec<u8> = g.perms[r].iter().map(|&s| tau[s as usize - 1]).collect();
                        crate::graph::rank(&w) as u32
                    })
                    .collect()
            })
            .collect();
        let inv_rank: Vec<u32> = (0..g.nfact)
            .map(|r| {
                let p = &g.perms[r];
                let mut inv = vec![0u8; n];
                for (i, &s) in p.iter().enumerate() {
                    inv[s as usize - 1] = i as u8 + 1;
                }
                crate::graph::rank(&inv) as u32
            })
            .collect();
        let cycle_map: Vec<Vec<u32>> = (0..g.nfact)
            .map(|t| {
                (0..g.cycle_count)
                    .map(|c| g.cycle_id[apply[t][reps[c] as usize] as usize])
                    .collect()
            })
            .collect();
        OrbitTables {
            apply,
            inv_rank,
            cycle_map,
        }
    }
}

/// Deterministic 128-bit mixing (splitmix64 doubled) — no RNG state.
#[inline]
fn mix128(seed: u64) -> u128 {
    #[inline]
    fn splitmix(mut z: u64) -> u64 {
        z = z.wrapping_add(0x9e3779b97f4a7c15);
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58476d1ce4e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d049bb133111eb);
        z ^ (z >> 31)
    }
    ((splitmix(seed) as u128) << 64) | splitmix(seed ^ 0xdead_beef_cafe_f00d) as u128
}

/// Pack the ledger + current-part scalar state into one word for
/// hashing (fields are disjoint: s:0..10, d3:10..16, d4:16..22,
/// d5:22..28, ip:28..40, cur_part:40..48).
fn pack_ledger(s: u16, d3: u16, d4: u16, d5: u16, ip: u16, cur_part: u8) -> u64 {
    debug_assert!(s < 1 << 10 && d3 < 1 << 6 && d4 < 1 << 6 && d5 < 1 << 6 && ip < 1 << 12);
    (s as u64)
        | (d3 as u64) << 10
        | (d4 as u64) << 16
        | (d5 as u64) << 22
        | (ip as u64) << 28
        | (cur_part as u64) << 40
}

impl SojournDfs<'_> {
    /// Run the exhaustive opening DFS from the identity permutation.
    pub fn run(&self) -> DfsStats {
        let g = self.g;
        // The move grammar (caps + profile + emergent-edge interiors),
        // shared with the NRPA rollouts.
        let mut grammar = Grammar::new(g, self.caps, self.profile.clone());
        grammar.fresh_doors = self.fresh_doors;
        let st = grammar.root(self.dump_per_class > 0);

        // Cycle representatives (lowest-ranked member), for necklace keys.
        let mut reps = vec![u32::MAX; g.cycle_count];
        for r in 0..g.nfact {
            let c = g.cycle_id[r] as usize;
            if reps[c] == u32::MAX {
                reps[c] = r as u32;
            }
        }

        let orbit = (self.dedup == DedupMode::Orbit).then(|| OrbitTables::new(g, &reps));

        let mut stats = DfsStats {
            nodes: 0,
            frontier: 0,
            canonical_classes: 0,
            oversize: false,
            dead_ends: 0,
            completed: 0,
            dump: Vec::new(),
        };
        let mut seen: HashSet<u128> = HashSet::new();
        let mut class_counts: HashMap<u128, u32> = HashMap::new();
        let mut classes: HashMap<u128, u64> = HashMap::new();
        let mut dump_counts: HashMap<u128, u32> = HashMap::new();
        let mut stack = vec![st];
        while let Some(st) = stack.pop() {
            if stats.nodes >= self.max_nodes {
                stats.oversize = true;
                break;
            }
            match self.dedup {
                DedupMode::Exact => {
                    if !seen.insert(self.state_hash(&st)) {
                        continue;
                    }
                }
                DedupMode::Orbit => {
                    if !seen.insert(self.orbit_hash(&st, orbit.as_ref().unwrap())) {
                        continue;
                    }
                }
                DedupMode::Abstraction => {
                    // exact duplicates never re-expand; beyond that, cap
                    // the number of exact exemplars expanded per class
                    if !seen.insert(self.state_hash(&st)) {
                        continue;
                    }
                    let c = class_counts
                        .entry(self.canonical_key(&st, &reps))
                        .or_insert(0);
                    if *c >= self.exemplars_per_class {
                        continue;
                    }
                    *c += 1;
                }
            }
            stats.nodes += 1;
            // Drift guard (s64 P3): in the library's own test build every
            // expanded state's shared visit bookkeeping is re-derived from
            // scratch and compared, so a wrong grammar update fails
            // immediately on a real DFS path. Compiled out of every
            // release build (see `counters_match_scratch_on_dfs_paths`).
            #[cfg(test)]
            {
                let scratch = crate::state::SearchState::recount(
                    g,
                    &st.cyc.visited,
                    st.cyc.cur,
                    st.cyc.len,
                    0,
                    None,
                );
                assert!(
                    st.cyc.counters_eq(&scratch.cyc),
                    "sojourn state drift\n  inc {}\n  ref {}",
                    st.cyc.counters(),
                    scratch.cyc.counters()
                );
            }
            if st.s > self.depth {
                stats.frontier += 1;
                let key = self.canonical_key(&st, &reps);
                *classes.entry(key).or_insert(0) += 1;
                if self.dump_per_class > 0 {
                    let c = dump_counts.entry(key).or_insert(0);
                    if *c < self.dump_per_class {
                        *c += 1;
                        stats.dump.push(FrontierSeed {
                            class_key: key,
                            len: st.cyc.len,
                            s: st.s,
                            d3: st.d3,
                            d4: st.d4,
                            d5: st.d5,
                            ip: st.ip,
                            path: st.path.clone().expect("dumping implies path tracking"),
                        });
                    }
                }
                continue;
            }
            if st.cyc.r == 0 {
                stats.completed += 1;
                continue;
            }
            let before = stack.len();
            for (_mv, c) in grammar.children(&st) {
                stack.push(c);
            }
            if stack.len() == before {
                stats.dead_ends += 1;
            }
        }
        stats.canonical_classes = classes.len();
        stats
    }

    fn state_hash(&self, st: &State) -> u128 {
        let mut h = mix128(st.cyc.cur as u64 ^ 0x51ed_2701);
        for (wi, &w) in st.cyc.visited.words().iter().enumerate() {
            if w != 0 {
                h ^= mix128(w ^ (wi as u64).wrapping_mul(0xabcd_ef01_2345_6789));
            }
        }
        h ^= mix128(pack_ledger(st.s, st.d3, st.d4, st.d5, st.ip, st.cur_part));
        for (c, &parts) in st.parts.iter().enumerate() {
            if parts != 0 {
                h ^= mix128(parts as u64 ^ ((c as u64) << 32) ^ 0x9e37_0001);
            }
        }
        h
    }

    /// Orbit-canonical hash: the state relabeled by the unique
    /// relabeling taking `cur` to the identity permutation. Sound
    /// quotient by the relabeling group (see [`DedupMode::Orbit`]).
    fn orbit_hash(&self, st: &State, tabs: &OrbitTables) -> u128 {
        let t = tabs.inv_rank[st.cyc.cur as usize] as usize;
        let row = &tabs.apply[t];
        let mut words = vec![0u64; st.cyc.visited.words().len()];
        for (wi, &w) in st.cyc.visited.words().iter().enumerate() {
            let mut bits = w;
            while bits != 0 {
                let b = bits.trailing_zeros() as usize;
                bits &= bits - 1;
                let img = row[(wi << 6) + b] as usize;
                words[img >> 6] |= 1u64 << (img & 63);
            }
        }
        let mut h = mix128(pack_ledger(st.s, st.d3, st.d4, st.d5, st.ip, st.cur_part));
        for (wi, &w) in words.iter().enumerate() {
            if w != 0 {
                h ^= mix128(w ^ (wi as u64).wrapping_mul(0xabcd_ef01_2345_6789));
            }
        }
        let cmap = &tabs.cycle_map[t];
        for (c, &parts) in st.parts.iter().enumerate() {
            if parts != 0 {
                h ^= mix128(parts as u64 ^ ((cmap[c] as u64) << 32) ^ 0x9e37_0001);
            }
        }
        h
    }

    /// L2 canonical key: relabeling-invariant opening-class identity.
    fn canonical_key(&self, st: &State, reps: &[u32]) -> u128 {
        let g = self.g;
        let n = g.n;
        let cur_cid = g.cycle_id[st.cyc.cur as usize] as usize;
        // per-cycle visit mask in rotation order rooted at the cycle
        // representative; canonical form = minimal rotation (necklace),
        // the current cycle carrying the walk position through the same
        // rotation; completed parts fold in (relabeling-invariant)
        let necklace = |mask: u8, mark: u8| -> u64 {
            let mut best = u64::MAX;
            for r in 0..n as u8 {
                let rm =
                    (((mask as u32) >> r | (mask as u32) << (n as u8 - r)) & ((1 << n) - 1)) as u64;
                let mp = if mark == u8::MAX {
                    0xff
                } else {
                    ((mark + n as u8 - r) % n as u8) as u64
                };
                best = best.min(rm << 8 | mp);
            }
            best
        };
        let mut multiset: Vec<u64> = Vec::new();
        let mut cur_key = 0u64;
        for (c, &rep) in reps.iter().enumerate() {
            if st.cyc.cycle_rem[c] as usize == g.n {
                continue; // untouched cycles carry no information
            }
            let mut mask = 0u8;
            let mut pos = u8::MAX;
            let mut m = rep;
            for i in 0..n {
                if st.cyc.visited.get(m as usize) {
                    mask |= 1 << i;
                }
                if m == st.cyc.cur {
                    pos = i as u8;
                }
                m = g.succ1(m);
            }
            if c == cur_cid {
                cur_key =
                    necklace(mask, pos) | (st.parts[c] as u64) << 20 | (st.cur_part as u64) << 44;
            } else {
                multiset.push(necklace(mask, u8::MAX) | (st.parts[c] as u64) << 20);
            }
        }
        multiset.sort_unstable();
        let mut h = mix128(cur_key ^ 0xc0ffee);
        h ^= mix128(pack_ledger(st.s, st.d3, st.d4, st.d5, st.ip, 0));
        for (i, m) in multiset.iter().enumerate() {
            h = h.wrapping_add(mix128(m ^ (i as u64) << 56));
        }
        h
    }
}

impl State {
    /// Advance within the current sojourn (ride or skip) to `target`,
    /// appending `w` characters.
    fn advance_within(&mut self, g: &Graph, target: u32, w: u32) {
        debug_assert_eq!(
            g.cycle_id[target as usize],
            g.cycle_id[self.cyc.cur as usize]
        );
        self.cyc.visit(g, target, w, None);
        self.cur_part += 1;
        if let Some(p) = self.path.as_mut() {
            p.push(target);
        }
    }
}

/// Interior permutation ranks per stored `w >= 3` edge, aligned with
/// `g.succs` indices (empty vecs for w < 3 slots).
pub fn build_interiors(g: &Graph) -> Vec<Vec<Vec<u32>>> {
    let n = g.n;
    (0..g.nfact)
        .map(|r| {
            let p = &g.perms[r];
            g.succs[r]
                .iter()
                .map(|&(q, w)| {
                    if w < 3 {
                        return Vec::new();
                    }
                    let qp = &g.perms[q as usize];
                    let mut v = Vec::new();
                    for j in 1..w as usize {
                        let mut win: Vec<u8> = p[j..].to_vec();
                        win.extend_from_slice(&qp[n - w as usize..n - w as usize + j]);
                        let mut mask = 0u16;
                        for &x in &win {
                            mask |= 1 << x;
                        }
                        if mask == ((1u16 << n) - 1) << 1 {
                            v.push(crate::graph::rank(&win) as u32);
                        }
                    }
                    v
                })
                .collect()
        })
        .collect()
}

